function expressionSource(count: number): string {
  const parts: string[] = [];
  for (let index = 1; index <= count; index++) {
    if (index > 1) parts.push(index % 2 === 0 ? " + " : " - ");
    parts.push(String(index), index % 3 === 0 ? " * 2" : "");
  }
  return parts.join("");
}

interface CommandResult {
  readonly success: boolean;
  readonly stdout: string;
  readonly stderr: string;
}

async function commandAvailable(commandName: string): Promise<boolean> {
  try {
    const result = await new Deno.Command(commandName, {
      args: ["--version"],
      stdout: "null",
      stderr: "null",
    }).output();
    return result.success;
  } catch (error) {
    if (error instanceof Deno.errors.NotFound) return false;
    throw error;
  }
}

function arrayBuffer(bytes: Uint8Array): ArrayBuffer {
  const copy = new Uint8Array(bytes.byteLength);
  copy.set(bytes);
  return copy.buffer as ArrayBuffer;
}

function assertWasmLimit(
  callback: () => unknown,
  errorClass: new (...args: never[]) => Error,
  code: string,
): void {
  try {
    callback();
  } catch (error) {
    assert(error instanceof errorClass);
    assertEquals((error as { code?: unknown }).code, code);
    return;
  }
  assert(false, `Expected Wasm resource limit ${code}.`);
}

async function runCommandResult(
  commandName: string,
  args: readonly string[],
): Promise<CommandResult> {
  const result = await new Deno.Command(commandName, {
    args: [...args],
    stdout: "piped",
    stderr: "piped",
  }).output();
  const decoder = new TextDecoder();
  return {
    success: result.success,
    stdout: decoder.decode(result.stdout),
    stderr: decoder.decode(result.stderr),
  };
}

