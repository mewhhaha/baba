Deno.test("Wasm parser instances run concurrently in workers", async () => {
  const result = compile(
    `
    token A = /a/ ;
    skip WS = /[ \\t\\r\\n]+/ ;
    module = items:item* ;
    item = A ;
  `,
    { targets: ["wasm"], wasm: legacySpecializedWasm },
  );
  assertEquals(result.diagnostics.length, 0);
  assert(result.bundle);

  const dir = await Deno.makeTempDir();
  const workers: Worker[] = [];
  try {
    await applyBundle(result.bundle, { root: dir });
    await Deno.writeTextFile(
      `${dir}/wasm_worker.ts`,
      `
        import { createParser } from "./wasm/mod.ts";

        const parser = createParser();
        const sibling = createParser();
        for (let index = 0; index < 250; index++) {
          const source = "a ".repeat((index % 7) + 1);
          const parsed = parser.parse(source);
          if (!parsed.ok) {
            throw new Error(\`worker parse failed at iteration \${index}\`);
          }
          parser.reset();

          const siblingParsed = sibling.parse(index % 2 === 0 ? "a" : "a a");
          if (!siblingParsed.ok) {
            throw new Error(\`worker sibling parse failed at iteration \${index}\`);
          }
          sibling.reset();
        }
        parser.dispose();
        sibling.dispose();
        self.postMessage({ ok: true });
      `,
    );

    const runWorker = (index: number): Promise<unknown> => {
      const worker = new Worker(new URL(`file://${dir}/wasm_worker.ts`), {
        type: "module",
        name: `wasm-parser-${index}`,
      });
      workers.push(worker);
      return new Promise((resolve, reject) => {
        worker.onmessage = (event) => {
          worker.terminate();
          resolve(event.data);
        };
        worker.onerror = (event) => {
          worker.terminate();
          reject(new Error(event.message));
        };
        worker.onmessageerror = () => {
          worker.terminate();
          reject(new Error("worker message could not be deserialized"));
        };
      });
    };

    const results = await Promise.all(
      Array.from({ length: 4 }, (_, index) => runWorker(index)),
    );
    assert(results.every((result) => (result as { ok?: unknown }).ok === true));
  } finally {
    for (const worker of workers) worker.terminate();
    await Deno.remove(dir, { recursive: true });
  }
});

