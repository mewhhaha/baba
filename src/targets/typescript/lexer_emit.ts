import type { TypeScriptTargetOptions } from "../../ast.ts";
import type { AnalyzedGrammar } from "../../compiler/ir.ts";

export function emitLexer(
  analyzed: AnalyzedGrammar,
  options: TypeScriptTargetOptions = {},
): string {
  const namedSpecs = analyzed.tokens
    .filter((token) =>
      token.kind === "skip" ||
      (token.kind === "token" && analyzed.reachableTokens.has(token.id))
    )
    .map((token) => ({
      kind: token.name,
      pattern: token.pattern,
      channel: token.kind === "skip" ? "trivia" : "main",
      order: token.declarationOrder,
    }));
  const literalSpecs = analyzed.literals
    .filter((literal) => analyzed.reachableLiterals.has(literal.id))
    .map((literal) => ({
      literal: literal.value,
      order: literal.sourceOrder,
    }));
  const preserveTrivia = options.preserveTrivia ?? true;

  return `// Generated by @mewhhaha/baba. Do not edit by hand.
import type {
  LexDiagnostic,
  LexOptions,
  LexResult,
  NamedTokenKind,
  Token,
} from "./syntax.ts";

const DEFAULT_PRESERVE_TRIVIA = ${JSON.stringify(preserveTrivia)};

const NAMED_SPECS: readonly {
  kind: NamedTokenKind;
  pattern: string;
  channel: "main" | "trivia";
  order: number;
}[] = ${JSON.stringify(namedSpecs, null, 2)} as const;

const LITERAL_SPECS: readonly {
  literal: string;
  order: number;
}[] = ${JSON.stringify(literalSpecs, null, 2)} as const;

const NAMED_REGEXES = NAMED_SPECS.map((spec) => ({
  ...spec,
  regex: new RegExp(\`^(?:\${spec.pattern})$\`),
}));

interface Candidate {
  type: "named" | "literal";
  text: string;
  length: number;
  order: number;
  specIndex: number;
}

export function lex(source: string, options: LexOptions = {}): LexResult {
  const preserveTrivia = options.preserveTrivia ?? DEFAULT_PRESERVE_TRIVIA;
  const tokens: Token[] = [];
  const diagnostics: LexDiagnostic[] = [];
  let offset = 0;

  while (offset < source.length) {
    const candidate = bestCandidate(source, offset);
    if (candidate) {
      const start = offset;
      const end = offset + candidate.length;
      if (candidate.type === "literal") {
        const spec = LITERAL_SPECS[candidate.specIndex];
        tokens.push({
          type: "literal",
          literal: spec.literal as never,
          text: spec.literal as never,
          span: { start, end },
          channel: "main",
        });
      } else {
        const spec = NAMED_SPECS[candidate.specIndex];
        if (spec.channel !== "trivia" || preserveTrivia) {
          tokens.push({
            type: "named",
            kind: spec.kind,
            text: candidate.text,
            span: { start, end },
            channel: spec.channel,
          });
        }
      }
      offset = end;
      continue;
    }

    const start = offset;
    const codePoint = source.codePointAt(offset);
    offset += codePoint !== undefined && codePoint > 0xffff ? 2 : 1;
    const text = source.slice(start, offset);
    tokens.push({
      type: "error",
      text,
      span: { start, end: offset },
      channel: "error",
    });
    diagnostics.push({
      code: "LEX_UNEXPECTED_CHARACTER",
      message: \`Unexpected character \${JSON.stringify(text)}.\`,
      span: { start, end: offset },
    });
  }

  tokens.push({
    type: "eof",
    text: "",
    span: { start: source.length, end: source.length },
    channel: "main",
  });
  return { source, tokens, diagnostics };
}

function bestCandidate(source: string, offset: number): Candidate | null {
  let best: Candidate | null = null;

  for (let specIndex = 0; specIndex < NAMED_REGEXES.length; specIndex++) {
    const spec = NAMED_REGEXES[specIndex];
    const text = longestRegexPrefix(spec.regex, source, offset);
    if (text.length === 0) continue;
    best = chooseBetter(best, {
      type: "named",
      text,
      length: text.length,
      order: spec.order,
      specIndex,
    });
  }

  for (let specIndex = 0; specIndex < LITERAL_SPECS.length; specIndex++) {
    const spec = LITERAL_SPECS[specIndex];
    if (spec.literal.length === 0) continue;
    if (!source.startsWith(spec.literal, offset)) continue;
    best = chooseBetter(best, {
      type: "literal",
      text: spec.literal,
      length: spec.literal.length,
      order: spec.order,
      specIndex,
    });
  }

  return best;
}

function longestRegexPrefix(
  regex: RegExp,
  source: string,
  offset: number,
): string {
  let best = "";
  for (let end = offset + 1; end <= source.length; end++) {
    const text = source.slice(offset, end);
    if (regex.test(text)) best = text;
  }
  return best;
}

function chooseBetter(current: Candidate | null, next: Candidate): Candidate {
  if (!current) return next;
  if (next.length !== current.length) {
    return next.length > current.length ? next : current;
  }
  if (next.type !== current.type) {
    return next.type === "literal" ? next : current;
  }
  return next.order < current.order ? next : current;
}
`;
}
