import type { PortableParserPlanMetadata } from "../runtime/portable_plan.ts";
import type { WasmModuleImage } from "./module_emit.ts";

export function emitWasmRuntime(
  image: WasmModuleImage,
  portableMetadata: PortableParserPlanMetadata,
): string {
  return `// Generated by @mewhhaha/baba. Do not edit by hand.
export const wasmTargetKind = "javascript-hosted-core-wasm" as const;
export const wasmBytes = new Uint8Array([
${byteLines(image.bytes)}
]);

const INPUT_BASE = ${image.inputBase};
const I32_BYTES = 4;
const LEX_RESULT_BYTES = 8;
const STATE_STACK_SLACK = 16;
const TOKEN_RECORD_BYTES = 12;
const TRACE_CAPACITY_FACTOR = 8;
const UTF16_UNIT_BYTES = 2;
const WASM_PAGE_BYTES = 65536;
const MAX_WASM_BYTES = 0xffff_ffff;
const MAX_WASM_PAGES = 65535;

interface ParserWasmExports {
  memory: WebAssembly.Memory;
  lex_one(sourcePtr: number, sourceLength: number, offset: number, resultPtr: number): number;
  lex_all(sourcePtr: number, sourceLength: number, resultPtr: number, tokenPtr: number): number;
  parse_trace(terminalsPtr: number, terminalCount: number, tracePtr: number, traceCapacity: number, stateStackPtr: number, errorPtr: number, branchPtr: number, branchCapacity: number, stateCapacity: number): number;
  parser_action(state: number, terminal: number): number;
  parser_goto(state: number, nonterminal: number): number;
  abi_version(): number;
  plan_version(): number;
  reset(): void;
}

const wasmModule = new WebAssembly.Module(wasmBytes);
const wasmInstance = new WebAssembly.Instance(wasmModule, {});
const wasm = wasmInstance.exports as unknown as ParserWasmExports;

export const memory = wasm.memory;
export const parserAction = wasm.parser_action;
export const parserGoto = wasm.parser_goto;
export const wasmAbiVersion = wasm.abi_version();
export const parserPlanFormat = ${
    JSON.stringify(portableMetadata.format)
  } as const;
export const parserPlanVersion = wasm.plan_version();
export const parserPlanSemantics = ${
    JSON.stringify(portableMetadata.semantics)
  } as const;
export const parserPlanHash = ${JSON.stringify(portableMetadata.hash)} as const;

export interface WasmSourceBuffer {
  sourcePtr: number;
  sourceLength: number;
  resultPtr: number;
  tokenPtr: number;
  tokenCapacity: number;
}

let cachedSource: string | null = null;
let cachedBuffer: WasmSourceBuffer | null = null;

export function reset(): void {
  wasm.reset();
  cachedSource = null;
  cachedBuffer = null;
}

export function writeSource(source: string): WasmSourceBuffer {
  if (cachedSource === source && cachedBuffer) return cachedBuffer;
  const sourcePtr = INPUT_BASE;
  const sourceBytes = checkedMul(
    source.length,
    UTF16_UNIT_BYTES,
    "source byte length",
  );
  const resultPtr = align4(
    checkedAdd(sourcePtr, sourceBytes, "lexer result offset"),
  );
  const tokenPtr = align4(
    checkedAdd(resultPtr, LEX_RESULT_BYTES, "token table offset"),
  );
  const tokenCapacity = source.length;
  const tokenBytes = checkedMul(
    tokenCapacity,
    TOKEN_RECORD_BYTES,
    "token table byte length",
  );
  ensureCapacity(checkedAdd(tokenPtr, tokenBytes, "token table end offset"));
  const units = new Uint16Array(memory.buffer, sourcePtr, source.length);
  for (let index = 0; index < source.length; index++) {
    units[index] = source.charCodeAt(index);
  }
  cachedSource = source;
  cachedBuffer = {
    sourcePtr,
    sourceLength: source.length,
    resultPtr,
    tokenPtr,
    tokenCapacity,
  };
  return cachedBuffer;
}

export function lexOne(buffer: WasmSourceBuffer, offset: number): {
  specIndex: number;
  end: number;
} | null {
  const matched = wasm.lex_one(
    buffer.sourcePtr,
    buffer.sourceLength,
    offset,
    buffer.resultPtr,
  );
  if (matched === 0) return null;
  const view = new DataView(memory.buffer);
  return {
    specIndex: view.getInt32(buffer.resultPtr, true),
    end: view.getInt32(buffer.resultPtr + 4, true),
  };
}

export function lexAll(buffer: WasmSourceBuffer): Int32Array {
  const count = wasm.lex_all(
    buffer.sourcePtr,
    buffer.sourceLength,
    buffer.resultPtr,
    buffer.tokenPtr,
  );
  return new Int32Array(memory.buffer, buffer.tokenPtr, count * 3);
}

export type ParseTraceResult =
  | { ok: true; trace: Int32Array }
  | { ok: false; state: number; index: number; internal: boolean };

export interface ParseTraceInput {
  terminals: Int32Array;
  terminalsPtr: number;
  terminalCapacity: number;
  traceCapacity: number;
}

export function createParseTraceInput(terminalCapacity: number): ParseTraceInput {
  assertPositiveInteger("terminalCapacity", terminalCapacity);
  const terminalsPtr = parseBase();
  const traceCapacity = Math.max(
    STATE_STACK_SLACK,
    checkedAdd(
      checkedMul(
        terminalCapacity,
        TRACE_CAPACITY_FACTOR,
        "trace capacity",
      ),
      STATE_STACK_SLACK,
      "trace capacity",
    ),
  );
  const tracePtr = align4(checkedAdd(
    terminalsPtr,
    checkedMul(terminalCapacity, I32_BYTES, "terminal byte length"),
    "trace offset",
  ));
  const stateStackPtr = align4(checkedAdd(
    tracePtr,
    checkedMul(traceCapacity, I32_BYTES, "trace byte length"),
    "state stack offset",
  ));
  const stateCapacity = checkedAdd(
    terminalCapacity,
    STATE_STACK_SLACK,
    "state stack capacity",
  );
  const errorPtr = align4(checkedAdd(
    stateStackPtr,
    checkedMul(stateCapacity, I32_BYTES, "state stack byte length"),
    "error record offset",
  ));
  ensureCapacity(checkedAdd(errorPtr, 8, "error record end offset"));
  return {
    terminals: new Int32Array(memory.buffer, terminalsPtr, terminalCapacity),
    terminalsPtr,
    terminalCapacity,
    traceCapacity,
  };
}

export function parseTrace(
  input: ParseTraceInput,
  terminalCount: number,
): ParseTraceResult {
  assertParseTraceInput(input);
  assertNonNegativeInteger("terminalCount", terminalCount);
  if (terminalCount > input.terminalCapacity) {
    throw new RangeError("terminalCount exceeds parse input terminalCapacity.");
  }
  let traceCapacity = input.traceCapacity;
  let branchCapacity = 0;
  while (true) {
    const tracePtr = align4(checkedAdd(
      input.terminalsPtr,
      checkedMul(input.terminalCapacity, I32_BYTES, "terminal byte length"),
      "trace offset",
    ));
    const stateStackPtr = align4(checkedAdd(
      tracePtr,
      checkedMul(traceCapacity, I32_BYTES, "trace byte length"),
      "state stack offset",
    ));
    const stateCapacity = checkedAdd(
      input.terminalCapacity,
      STATE_STACK_SLACK,
      "state stack capacity",
    );
    const errorPtr = align4(checkedAdd(
      stateStackPtr,
      checkedMul(stateCapacity, I32_BYTES, "state stack byte length"),
      "error record offset",
    ));
    const branchStride = checkedAdd(
      checkedAdd(4, stateCapacity, "branch state stride"),
      traceCapacity,
      "branch trace stride",
    );
    const branchPtr = align4(checkedAdd(errorPtr, 8, "branch table offset"));
    const branchBytes = checkedMul(
      checkedMul(branchCapacity, branchStride, "branch table cells"),
      I32_BYTES,
      "branch table byte length",
    );
    ensureCapacity(checkedAdd(branchPtr, branchBytes, "branch table end offset"));

    const count = wasm.parse_trace(
      input.terminalsPtr,
      terminalCount,
      tracePtr,
      traceCapacity,
      stateStackPtr,
      errorPtr,
      branchPtr,
      branchCapacity,
      stateCapacity,
    );
    if (count === -2) {
      traceCapacity = checkedMul(traceCapacity, 2, "trace capacity");
      continue;
    }
    if (count === -4) {
      branchCapacity = branchCapacity === 0
        ? Math.max(
          STATE_STACK_SLACK,
          checkedMul(terminalCount, 2, "branch capacity"),
        )
        : checkedMul(branchCapacity, 2, "branch capacity");
      continue;
    }
    if (count < 0) {
      const view = new DataView(memory.buffer);
      return {
        ok: false,
        state: view.getInt32(errorPtr, true),
        index: view.getInt32(errorPtr + 4, true),
        internal: count !== -1,
      };
    }
    return {
      ok: true,
      trace: new Int32Array(memory.buffer, tracePtr, count),
    };
  }
}

function ensureCapacity(requiredBytes: number): void {
  assertNonNegativeInteger("requiredBytes", requiredBytes);
  if (requiredBytes > MAX_WASM_BYTES) {
    throw new RangeError("requiredBytes exceeds the 32-bit Wasm address space.");
  }
  const current = memory.buffer.byteLength;
  if (requiredBytes <= current) return;
  const requiredPages = Math.ceil(requiredBytes / WASM_PAGE_BYTES);
  const currentPages = current / WASM_PAGE_BYTES;
  if (requiredPages > MAX_WASM_PAGES) {
    throw new RangeError("requiredBytes exceeds the configured Wasm page limit.");
  }
  memory.grow(requiredPages - currentPages);
}

function align4(value: number): number {
  assertNonNegativeInteger("byte offset", value);
  const remainder = value % I32_BYTES;
  return remainder === 0
    ? value
    : checkedAdd(value, I32_BYTES - remainder, "aligned byte offset");
}

function parseBase(): number {
  if (!cachedBuffer) return INPUT_BASE;
  return align4(
    checkedAdd(
      cachedBuffer.tokenPtr,
      checkedMul(
        cachedBuffer.tokenCapacity,
        TOKEN_RECORD_BYTES,
        "token table byte length",
      ),
      "parse base",
    ),
  );
}

function assertParseTraceInput(input: ParseTraceInput): void {
  assertNonNegativeInteger("terminalsPtr", input.terminalsPtr);
  assertPositiveInteger("terminalCapacity", input.terminalCapacity);
  assertPositiveInteger("traceCapacity", input.traceCapacity);
}

function assertPositiveInteger(name: string, value: number): void {
  if (!Number.isInteger(value) || value <= 0) {
    throw new RangeError(name + " must be a positive integer.");
  }
}

function assertNonNegativeInteger(name: string, value: number): void {
  if (!Number.isInteger(value) || value < 0) {
    throw new RangeError(name + " must be a non-negative integer.");
  }
}

function checkedAdd(left: number, right: number, label: string): number {
  assertNonNegativeInteger(label, left);
  assertNonNegativeInteger(label, right);
  const value = left + right;
  if (!Number.isSafeInteger(value) || value > MAX_WASM_BYTES) {
    throw new RangeError(label + " exceeds the 32-bit Wasm address space.");
  }
  return value;
}

function checkedMul(left: number, right: number, label: string): number {
  assertNonNegativeInteger(label, left);
  assertNonNegativeInteger(label, right);
  const value = left * right;
  if (!Number.isSafeInteger(value) || value > MAX_WASM_BYTES) {
    throw new RangeError(label + " exceeds the 32-bit Wasm address space.");
  }
  return value;
}
`;
}

function byteLines(bytes: Uint8Array): string {
  const lines: string[] = [];
  for (let index = 0; index < bytes.length; index += 16) {
    lines.push(
      `  ${
        [...bytes.slice(index, index + 16)].map((byte) =>
          `0x${byte.toString(16).padStart(2, "0")}`
        ).join(", ")
      },`,
    );
  }
  return lines.join("\n");
}
